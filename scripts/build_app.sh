#!/usr/bin/env bash
# Builds Handsfree.app from a clean checkout, with no manual Xcode steps.
#
#   scripts/build_app.sh             Release build, signed, at build/Handsfree.app
#   scripts/build_app.sh --debug     Debug build instead
#   scripts/build_app.sh --test      Also run the unit tests (HandsfreeTests)
#   scripts/build_app.sh --generate-only   Only write Handsfree.xcodeproj (to open it in Xcode)
#
# Why signing matters: macOS ties the Microphone, Accessibility and Screen
# Recording grants to the app's code signature. An ad-hoc signature changes on
# every build, so every rebuild would look like a new app and lose its grants.
# This script signs with one Apple Development certificate, chosen once and
# remembered in build/signing-identity, so the signature's identity (its
# "designated requirement") stays the same from build to build.
#
# Override the identity with HANDSFREE_SIGN_IDENTITY=<SHA-1 fingerprint>.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$REPO_ROOT"

CONFIGURATION="Release"
RUN_TESTS=0
GENERATE_ONLY=0
for argument in "$@"; do
  case "$argument" in
    --debug) CONFIGURATION="Debug" ;;
    --test) RUN_TESTS=1 ;;
    --generate-only) GENERATE_ONLY=1 ;;
    -h|--help) sed -n '2,20p' "$0"; exit 0 ;;
    *) echo "Unknown option: $argument" >&2; exit 2 ;;
  esac
done

BUILD_DIR="$REPO_ROOT/build"
GENERATED_DIR="$BUILD_DIR/generated"
LOG_DIR="$BUILD_DIR/logs"
mkdir -p "$GENERATED_DIR" "$LOG_DIR"

say() { printf '\033[1m==> %s\033[0m\n' "$*"; }
note() { printf '    %s\n' "$*"; }

# ---------------------------------------------------------------------------
# 0. Tools
# ---------------------------------------------------------------------------
if ! command -v xcodegen >/dev/null 2>&1; then
  echo "XcodeGen is not installed. Install it with: brew install xcodegen" >&2
  exit 1
fi
if ! command -v xcodebuild >/dev/null 2>&1; then
  echo "xcodebuild is missing. Install Xcode 26 and run: sudo xcode-select -s /Applications/Xcode.app" >&2
  exit 1
fi

# ---------------------------------------------------------------------------
# 1. Decide which local packages to link
# ---------------------------------------------------------------------------
say "Checking local packages"
LINKED_PACKAGES=()
while IFS= read -r line || [ -n "$line" ]; do
  package_name="$(echo "${line%%#*}" | tr -d '[:space:]')"
  [ -z "$package_name" ] && continue
  package_dir="$REPO_ROOT/Packages/$package_name"
  if [ ! -f "$package_dir/Package.swift" ]; then
    note "$package_name: not in Packages/ yet -> using the app's stand-in"
    continue
  fi
  # Build in our own scratch folder so we never fight the package owner's
  # own `swift build` over Packages/<Name>/.build.
  # If it fails, try once more from an empty folder: SwiftPM's cached build plan
  # can miss a file newly added to HFCore and report a false failure.
  check_dir="$BUILD_DIR/package-check/$package_name"
  # A link left by the de-duplication below can dangle if DerivedData was deleted.
  if [ -L "$check_dir/artifacts" ] && [ ! -e "$check_dir/artifacts" ]; then rm -f "$check_dir/artifacts"; fi
  if swift build --package-path "$package_dir" --scratch-path "$check_dir" >"$LOG_DIR/package-$package_name.log" 2>&1 \
     || { rm -rf "$check_dir"; swift build --package-path "$package_dir" --scratch-path "$check_dir" >"$LOG_DIR/package-$package_name.log" 2>&1; }; then
    note "$package_name: compiles -> linked"
    LINKED_PACKAGES+=("$package_name")
  else
    note "$package_name: does not compile yet (see build/logs/package-$package_name.log) -> using the app's stand-in"
  fi
done < "$REPO_ROOT/Handsfree/LinkedPackages.txt"

{
  echo "# Generated by scripts/build_app.sh from Handsfree/LinkedPackages.txt. Do not edit."
  if [ ${#LINKED_PACKAGES[@]} -eq 0 ]; then
    echo "packages: {}"
  else
    echo "packages:"
    for package_name in "${LINKED_PACKAGES[@]}"; do
      echo "  $package_name:"
      echo "    path: Packages/$package_name"
    done
    echo "targets:"
    echo "  Handsfree:"
    echo "    dependencies:"
    for package_name in "${LINKED_PACKAGES[@]}"; do
      echo "      - package: $package_name"
    done
  fi
} > "$GENERATED_DIR/linked-packages.yml"

# When the set of linked packages changes, throw away the previous build
# products. Otherwise a package that was linked last time leaves its compiled
# module behind, `#if canImport(<Name>)` still finds it, and the compiler loads
# a stale module (it crashed doing exactly that). Downloaded package checkouts
# in build/DerivedData/SourcePackages are kept.
linked_list_file="$GENERATED_DIR/linked-packages.txt"
current_linked_list="${LINKED_PACKAGES[*]:-}"
if [ ! -f "$linked_list_file" ] || [ "$(cat "$linked_list_file")" != "$current_linked_list" ]; then
  if [ -d "$BUILD_DIR/DerivedData/Build" ]; then
    note "Linked packages changed since the last build: clearing old build products"
    rm -rf "$BUILD_DIR/DerivedData/Build"
  fi
  echo "$current_linked_list" > "$linked_list_file"
fi

# ---------------------------------------------------------------------------
# 2. Generate the Xcode project
# ---------------------------------------------------------------------------
say "Generating Handsfree.xcodeproj"
xcodegen generate --spec "$REPO_ROOT/project.yml" --quiet
if [ "$GENERATE_ONLY" -eq 1 ]; then
  note "Done. Open Handsfree.xcodeproj in Xcode."
  exit 0
fi

# ---------------------------------------------------------------------------
# 3. Choose a stable signing identity
# ---------------------------------------------------------------------------
say "Choosing a signing identity"
IDENTITY_FILE="$BUILD_DIR/signing-identity"
available_identities="$(security find-identity -v -p codesigning 2>/dev/null || true)"
SIGN_IDENTITY="${HANDSFREE_SIGN_IDENTITY:-}"
if [ -z "$SIGN_IDENTITY" ] && [ -f "$IDENTITY_FILE" ]; then
  remembered="$(cat "$IDENTITY_FILE")"
  if echo "$available_identities" | grep -q -- "$remembered"; then
    SIGN_IDENTITY="$remembered"
  fi
fi
if [ -z "$SIGN_IDENTITY" ]; then
  SIGN_IDENTITY="$(echo "$available_identities" | grep '"Apple Development' | head -n 1 | awk '{print $2}')"
fi

TEAM_ID=""
if [ -n "$SIGN_IDENTITY" ]; then
  echo "$SIGN_IDENTITY" > "$IDENTITY_FILE"
  # The team is the certificate's Organisational Unit. Find the certificate by
  # its fingerprint, because two certificates can share one name.
  # (awk reads to the end rather than exiting early: with pipefail, an early
  # exit would kill `security` with a broken pipe and stop the script.)
  certificate_pem="$(security find-certificate -a -Z -p 2>/dev/null \
    | awk -v fingerprint="$SIGN_IDENTITY" '
        /^SHA-1 hash:/ { capture = ($3 == fingerprint); next }
        capture && !done { print }
        capture && /END CERTIFICATE/ { done = 1 }' || true)"
  TEAM_ID="$(printf '%s\n' "$certificate_pem" | openssl x509 -noout -subject 2>/dev/null \
    | sed -n 's/.*OU *= *\([A-Z0-9]*\).*/\1/p' || true)"
  identity_name="$(echo "$available_identities" | grep "$SIGN_IDENTITY" | sed 's/.*"\(.*\)".*/\1/' | head -n 1)"
  note "Identity: $identity_name"
  note "Fingerprint: $SIGN_IDENTITY (remembered in build/signing-identity)"
  note "Team: ${TEAM_ID:-unknown}"
  SIGNING_SETTINGS=(CODE_SIGN_STYLE=Manual "CODE_SIGN_IDENTITY=$SIGN_IDENTITY" "DEVELOPMENT_TEAM=$TEAM_ID" PROVISIONING_PROFILE_SPECIFIER= OTHER_CODE_SIGN_FLAGS=--timestamp=none)
else
  echo "WARNING: no Apple Development identity in the keychain. Signing ad hoc." >&2
  echo "WARNING: macOS will treat every rebuild as a new app and forget its permissions." >&2
  SIGNING_SETTINGS=(CODE_SIGN_STYLE=Manual CODE_SIGN_IDENTITY=- DEVELOPMENT_TEAM= PROVISIONING_PROFILE_SPECIFIER=)
fi

# ---------------------------------------------------------------------------
# 4. Build (and optionally test)
# ---------------------------------------------------------------------------
say "Building Handsfree ($CONFIGURATION)"
build_log="$LOG_DIR/xcodebuild.log"
if ! xcodebuild build \
      -project "$REPO_ROOT/Handsfree.xcodeproj" \
      -scheme Handsfree \
      -configuration "$CONFIGURATION" \
      -destination 'platform=macOS,arch=arm64' \
      -derivedDataPath "$BUILD_DIR/DerivedData" \
      ONLY_ACTIVE_ARCH=YES \
      "${SIGNING_SETTINGS[@]}" \
      >"$build_log" 2>&1; then
  echo "Build failed. The errors:" >&2
  grep -E "error:|BUILD FAILED" "$build_log" | sort -u | head -n 40 >&2 || tail -n 40 "$build_log" >&2
  echo "Full log: build/logs/xcodebuild.log" >&2
  exit 1
fi
warnings="$(grep -c "warning:" "$build_log" || true)"
note "Built. ($warnings compiler warning lines; full log in build/logs/xcodebuild.log)"

if [ "$RUN_TESTS" -eq 1 ]; then
  say "Running unit tests"
  test_log="$LOG_DIR/xcodebuild-test.log"
  if xcodebuild test \
        -project "$REPO_ROOT/Handsfree.xcodeproj" \
        -scheme Handsfree \
        -destination 'platform=macOS,arch=arm64' \
        -derivedDataPath "$BUILD_DIR/DerivedData" \
        -only-testing:HandsfreeTests \
        "${SIGNING_SETTINGS[@]}" \
        >"$test_log" 2>&1; then
    grep -E "Test run with|Executed [0-9]+ test|passed after|TEST SUCCEEDED" "$test_log" | tail -n 5 | sed 's/^/    /'
  else
    echo "Tests failed:" >&2
    grep -E "error:|failed|✘|issue" "$test_log" | head -n 40 >&2
    echo "Full log: build/logs/xcodebuild-test.log" >&2
    exit 1
  fi
fi

# ---------------------------------------------------------------------------
# 5. Put the app at a stable path and check its signature
# ---------------------------------------------------------------------------
# Binary frameworks (the ElevenLabs SDK brings about 2.3 GB) are unpacked once by
# the package check and once by Xcode, in the same layout. Keep one copy: point
# the check's folder at Xcode's. (The download itself is cached once by SwiftPM.)
shared_artifacts="$BUILD_DIR/DerivedData/SourcePackages/artifacts"
for check_dir in "$BUILD_DIR"/package-check/*; do
  if [ -d "$check_dir/artifacts" ] && [ ! -L "$check_dir/artifacts" ] && [ -d "$shared_artifacts" ] \
     && diff -q <(cd "$check_dir/artifacts" && find . -maxdepth 3 | sort) <(cd "$shared_artifacts" && find . -maxdepth 3 | sort) >/dev/null; then
    rm -rf "$check_dir/artifacts" && ln -s "$shared_artifacts" "$check_dir/artifacts"
    note "Shared the unpacked binary frameworks of $(basename "$check_dir") with Xcode's copy"
  fi
done

built_app="$BUILD_DIR/DerivedData/Build/Products/$CONFIGURATION/Handsfree.app"
final_app="$BUILD_DIR/Handsfree.app"
rm -rf "$final_app"
ditto "$built_app" "$final_app"

say "Checking the signature"
codesign --verify --deep --strict "$final_app"
note "Signature valid."
note "Designated requirement (what macOS remembers permissions against):"
codesign -d -r- "$final_app" 2>&1 | sed -n 's/^designated => /      /p'
note "Linked packages: HFCore ${LINKED_PACKAGES[*]:-}"
say "Done: build/Handsfree.app   (launch it with scripts/run_app.sh)"
